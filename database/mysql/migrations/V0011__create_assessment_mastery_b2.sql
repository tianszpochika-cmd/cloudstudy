CREATE TABLE IF NOT EXISTS asm_question_version (
  question_id BIGINT UNSIGNED NOT NULL,
  question_version VARCHAR(32) NOT NULL,
  question_type VARCHAR(32) NOT NULL,
  item_id BIGINT UNSIGNED NULL,
  prompt_json JSON NOT NULL,
  interaction_json JSON NOT NULL,
  scoring_policy_json JSON NOT NULL,
  answer_key_json JSON NOT NULL COMMENT '服务端受保护字段；禁止出现在 learner response/event payload',
  error_categories_json JSON NOT NULL,
  content_status VARCHAR(16) NOT NULL DEFAULT 'PUBLISHED',
  content_hash CHAR(64) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (question_id, question_version),
  KEY idx_asm_question_type_status (question_type, content_status),
  CONSTRAINT chk_asm_question_type CHECK (question_type IN ('CHOICE','CONNECT_LINE','DRAG_SORTER','FILL_BLANK','SPELL_INPUT','LISTEN_CHOICE','ERROR_CORRECTION','TRANSLATION_INPUT')),
  CONSTRAINT chk_asm_question_prompt CHECK (JSON_TYPE(prompt_json) = 'OBJECT'),
  CONSTRAINT chk_asm_question_interaction CHECK (JSON_TYPE(interaction_json) = 'OBJECT'),
  CONSTRAINT chk_asm_question_scoring CHECK (JSON_TYPE(scoring_policy_json) = 'OBJECT'),
  CONSTRAINT chk_asm_question_answer_key CHECK (JSON_TYPE(answer_key_json) = 'OBJECT')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='不可变题目版本；答案只在服务端评分边界可见';

