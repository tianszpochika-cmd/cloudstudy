-- B10 learning/assessment/content snapshot and reliability baseline.
--
-- This repository-level migration is an additive, deterministic compatibility fixture.
-- Production services execute equivalent tables in their own Flyway schemas and credentials:
-- content-service owns cnt_b10_*, assessment-service owns asm_b10_*, learning-service owns
-- lrn_b10_*, workflow owns wf_b10_*, and the migration adapter owns cmp_b10_*.
-- Cross-service identifiers are scalar references only: there are deliberately no cross-owner
-- foreign keys, shared writes, Kafka RPC semantics, or answer-rule payloads in events.

CREATE TABLE IF NOT EXISTS `cnt_b10_content_snapshot` (
  `snapshot_id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `tenant_id` VARCHAR(64) NOT NULL DEFAULT 'platform',
  `content_code` VARCHAR(128) NOT NULL,
  `content_version_id` BIGINT UNSIGNED NOT NULL,
  `version_number` INT UNSIGNED NOT NULL,
  `content_epoch` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `snapshot_hash` CHAR(64) NOT NULL,
  `snapshot_status` VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
  `grading_rule_set_version` VARCHAR(96) NOT NULL,
  `sealed_rule_manifest_json` JSON NOT NULL,
  `learner_items_json` JSON NOT NULL,
  `assessment_item_manifest_json` JSON NOT NULL,
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `invalidated_at` DATETIME(6) NULL,
  PRIMARY KEY (`snapshot_id`),
  UNIQUE KEY `uk_cnt_b10_snapshot_hash` (`tenant_id`, `content_version_id`, `snapshot_hash`),
  KEY `idx_cnt_b10_snapshot_lookup` (`tenant_id`, `content_code`, `content_version_id`, `snapshot_status`),
  CONSTRAINT `chk_cnt_b10_snapshot_tenant` CHECK (`tenant_id` = 'platform'),
  CONSTRAINT `chk_cnt_b10_snapshot_hash` CHECK (`snapshot_hash` REGEXP '^[0-9A-Fa-f]{64}$'),
  CONSTRAINT `chk_cnt_b10_snapshot_status` CHECK (`snapshot_status` IN ('ACTIVE', 'INVALIDATED', 'RECOVERABLE', 'ARCHIVED')),
  CONSTRAINT `chk_cnt_b10_snapshot_rules` CHECK (JSON_TYPE(`sealed_rule_manifest_json`) = 'OBJECT'),
  CONSTRAINT `chk_cnt_b10_snapshot_learner_items` CHECK (JSON_TYPE(`learner_items_json`) = 'ARRAY'),
  CONSTRAINT `chk_cnt_b10_snapshot_assessment_items` CHECK (JSON_TYPE(`assessment_item_manifest_json`) = 'ARRAY')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='B10 content-service immutable snapshot and protected rule manifest';

