-- Foundation migration 0003.
-- Consumers must use event_id/dedupe_key as their own idempotent boundary.
CREATE TABLE IF NOT EXISTS outbox_events (
  outbox_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  event_id CHAR(36) NOT NULL,
  owner_domain VARCHAR(48) NOT NULL,
  aggregate_type VARCHAR(64) NOT NULL,
  aggregate_id VARCHAR(128) NOT NULL,
  event_type VARCHAR(128) NOT NULL,
  event_version VARCHAR(32) NOT NULL,
  dedupe_key VARCHAR(192) NOT NULL,
  payload_json JSON NOT NULL,
  headers_json JSON NULL,
  actor_subject VARCHAR(128) NULL,
  request_id VARCHAR(80) NULL,
  occurred_at DATETIME(6) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
  available_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  locked_by VARCHAR(128) NULL,
  locked_until DATETIME(6) NULL,
  published_at DATETIME(6) NULL,
  last_error_code VARCHAR(64) NULL,
  last_error_message VARCHAR(255) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (outbox_id),
  UNIQUE KEY uk_outbox_event_id (event_id),
  UNIQUE KEY uk_outbox_dedupe_key (dedupe_key),
  KEY idx_outbox_dispatch (status, available_at, outbox_id),
  KEY idx_outbox_lock (locked_until, status, outbox_id),
  KEY idx_outbox_aggregate (aggregate_type, aggregate_id, occurred_at),
  KEY idx_outbox_event_type (event_type, occurred_at),
  CONSTRAINT chk_outbox_status CHECK (status IN ('PENDING', 'IN_FLIGHT', 'PUBLISHED', 'FAILED', 'DEAD_LETTER')),
  CONSTRAINT chk_outbox_attempt_count CHECK (attempt_count >= 0),
  CONSTRAINT chk_outbox_published_time CHECK (status <> 'PUBLISHED' OR published_at IS NOT NULL),
  CONSTRAINT chk_outbox_payload_object CHECK (JSON_TYPE(payload_json) = 'OBJECT'),
  CONSTRAINT chk_outbox_event_id CHECK (event_id REGEXP '^[0-9a-fA-F-]{36}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='事务内写入、至少一次投递的事件出站表';
