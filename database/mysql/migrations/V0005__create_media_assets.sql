-- Foundation migration 0005.
-- The row describes an object, not the object bytes. Bytes remain in S3-compatible
-- storage and are never embedded in MySQL or development fixtures.
CREATE TABLE IF NOT EXISTS media_assets (
  media_asset_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  asset_uuid CHAR(36) NOT NULL,
  asset_key VARCHAR(160) NOT NULL,
  asset_kind VARCHAR(32) NOT NULL,
  storage_provider VARCHAR(32) NOT NULL,
  bucket_name VARCHAR(128) NOT NULL,
  object_key VARCHAR(512) NOT NULL,
  object_version VARCHAR(128) NULL,
  object_identity_hash BINARY(32) GENERATED ALWAYS AS (
    UNHEX(SHA2(CONCAT_WS(CHAR(0), storage_provider, bucket_name, object_key, COALESCE(object_version, '')), 256))
  ) STORED,
  content_hash CHAR(64) NOT NULL,
  content_hash_algorithm VARCHAR(16) NOT NULL DEFAULT 'SHA-256',
  mime_type VARCHAR(128) NOT NULL,
  content_length_bytes BIGINT UNSIGNED NOT NULL,
  etag VARCHAR(128) NULL,
  duration_ms INT UNSIGNED NULL,
  sample_rate_hz INT UNSIGNED NULL,
  channel_count TINYINT UNSIGNED NULL,
  codec VARCHAR(32) NULL,
  owner_type VARCHAR(32) NOT NULL,
  owner_id VARCHAR(128) NOT NULL,
  visibility VARCHAR(24) NOT NULL DEFAULT 'PRIVATE',
  storage_status VARCHAR(16) NOT NULL DEFAULT 'UPLOADING',
  supports_range TINYINT(1) NOT NULL DEFAULT 1,
  chunk_size_bytes INT UNSIGNED NULL,
  part_count INT UNSIGNED NULL,
  last_modified_at DATETIME(6) NULL,
  content_disposition VARCHAR(255) NULL,
  copyright_owner VARCHAR(160) NULL,
  license_code VARCHAR(96) NULL,
  license_url VARCHAR(512) NULL,
  license_starts_at DATETIME(6) NULL,
  license_expires_at DATETIME(6) NULL,
  attribution_required TINYINT(1) NOT NULL DEFAULT 0,
  rights_metadata_json JSON NULL,
  retention_policy_code VARCHAR(64) NOT NULL DEFAULT 'STANDARD_MEDIA',
  retention_until DATETIME(6) NULL,
  deletion_requested_at DATETIME(6) NULL,
  created_by VARCHAR(128) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (media_asset_id),
  UNIQUE KEY uk_media_asset_uuid (asset_uuid),
  UNIQUE KEY uk_media_asset_key_version (asset_key, object_version),
  UNIQUE KEY uk_media_object_version (object_identity_hash),
  KEY idx_media_hash_kind (content_hash, asset_kind),
  KEY idx_media_owner_visibility (owner_type, owner_id, visibility, storage_status),
  KEY idx_media_status_retention (storage_status, retention_until, media_asset_id),
  KEY idx_media_license_expiry (license_expires_at, storage_status),
  CONSTRAINT chk_media_asset_uuid CHECK (asset_uuid REGEXP '^[0-9a-fA-F-]{36}$'),
  CONSTRAINT chk_media_hash CHECK (content_hash REGEXP '^[0-9a-fA-F]{64}$' AND content_hash_algorithm = 'SHA-256'),
  CONSTRAINT chk_media_size CHECK (content_length_bytes > 0),
  CONSTRAINT chk_media_kind CHECK (asset_kind IN ('AUDIO', 'IMAGE', 'VIDEO', 'DOCUMENT', 'MODEL_3D', 'SVG', 'WAVEFORM', 'OFFLINE_BUNDLE', 'OTHER')),
  CONSTRAINT chk_media_visibility CHECK (visibility IN ('PRIVATE', 'OWNER', 'GROUP', 'AUTHENTICATED', 'PUBLIC', 'INTERNAL')),
  CONSTRAINT chk_media_status CHECK (storage_status IN ('UPLOADING', 'ACTIVE', 'REVOKED', 'DELETED')),
  CONSTRAINT chk_media_range_metadata CHECK (
    supports_range = 0 OR (chunk_size_bytes IS NOT NULL AND chunk_size_bytes > 0 AND part_count IS NOT NULL AND part_count > 0)
  ),
  CONSTRAINT chk_media_license_window CHECK (license_expires_at IS NULL OR license_starts_at IS NULL OR license_expires_at > license_starts_at),
  CONSTRAINT chk_media_retention_window CHECK (retention_until IS NULL OR retention_until >= created_at),
  CONSTRAINT chk_media_deletion_status CHECK (deletion_requested_at IS NULL OR storage_status IN ('REVOKED', 'DELETED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='S3 对象元数据、版权、可见性与断点下载信息';
