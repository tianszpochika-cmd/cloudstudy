-- B11 additive migration: media-service, notification-service and offline/workflow boundaries.
-- Media metadata owns hashes and references only; no raw media, object URL, answer content or token content is stored.
-- Compatibility records are append-only evidence and never rewrite B3 domain facts.

CREATE TABLE IF NOT EXISTS `med_b11_asset` (
  `asset_id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `asset_ref` VARCHAR(128) NOT NULL,
  `tenant_id` VARCHAR(64) NOT NULL DEFAULT 'platform',
  `owner_scope` VARCHAR(16) NOT NULL DEFAULT 'PLATFORM',
  `owner_principal_id` VARCHAR(128) NULL,
  `content_version_id` BIGINT UNSIGNED NOT NULL,
  `kind` VARCHAR(32) NOT NULL,
  `mime_type` VARCHAR(128) NOT NULL,
  `byte_length` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `duration_ms` BIGINT UNSIGNED NULL,
  `checksum_sha256` CHAR(64) NOT NULL,
  `rights_ref_hash` CHAR(64) NOT NULL,
  `rights_status` VARCHAR(16) NOT NULL DEFAULT 'AUTHORIZED',
  `asset_status` VARCHAR(16) NOT NULL DEFAULT 'PROCESSING',
  `transcode_status` VARCHAR(16) NOT NULL DEFAULT 'NOT_REQUESTED',
  `transcode_error_code` VARCHAR(96) NULL,
  `storage_provider` VARCHAR(32) NOT NULL DEFAULT 'S3_COMPATIBLE',
  `object_ref_hash` CHAR(64) NOT NULL,
  `asset_version` BIGINT UNSIGNED NOT NULL DEFAULT 1,
  `retention_until` DATETIME(6) NULL,
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (`asset_id`),
  UNIQUE KEY `uk_med_b11_asset_ref` (`tenant_id`, `asset_ref`),
  UNIQUE KEY `uk_med_b11_asset_object_version` (`object_ref_hash`, `asset_version`),
  KEY `idx_med_b11_asset_rights` (`tenant_id`, `content_version_id`, `rights_status`, `asset_status`),
  CONSTRAINT `chk_med_b11_asset_tenant` CHECK (`tenant_id` = 'platform'),
  CONSTRAINT `chk_med_b11_asset_owner` CHECK ((`owner_scope` = 'PLATFORM' AND `owner_principal_id` IS NULL) OR (`owner_scope` = 'PRINCIPAL' AND `owner_principal_id` IS NOT NULL)),
  CONSTRAINT `chk_med_b11_asset_kind` CHECK (`kind` IN ('AUDIO_TRACK', 'VIDEO_TRACK', 'IMAGE', 'WAVEFORM', 'SUBTITLE', 'PHONETICS_2D', 'THREE_D_MODEL')),
  CONSTRAINT `chk_med_b11_asset_rights` CHECK (`rights_status` IN ('AUTHORIZED', 'PENDING', 'REVOKED', 'EXPIRED')),
  CONSTRAINT `chk_med_b11_asset_status` CHECK (`asset_status` IN ('READY', 'PROCESSING', 'FAILED', 'REVOKED', 'DELETED')),
  CONSTRAINT `chk_med_b11_asset_transcode` CHECK (`transcode_status` IN ('NOT_REQUESTED', 'PENDING', 'RUNNING', 'SUCCEEDED', 'FAILED')),
  CONSTRAINT `chk_med_b11_asset_checksum` CHECK (`checksum_sha256` REGEXP '^[A-Fa-f0-9]{64}$'),
  CONSTRAINT `chk_med_b11_asset_rights_hash` CHECK (`rights_ref_hash` REGEXP '^[A-Fa-f0-9]{64}$'),
  CONSTRAINT `chk_med_b11_asset_object_hash` CHECK (`object_ref_hash` REGEXP '^[A-Fa-f0-9]{64}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='B11 media metadata; no raw object key or bytes';

