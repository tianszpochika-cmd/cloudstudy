import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {verifyArtifact,artifact,gitSnapshot} from '../../../../../../../scripts/lib/redesign-task-state.mjs';
const dir=path.dirname(fileURLToPath(import.meta.url)),root=process.cwd();
const index=JSON.parse(fs.readFileSync('docs/06-design/v2-980plus/redesign/dev-plan-R1.tasks.json'));
const state=JSON.parse(fs.readFileSync('docs/06-design/v2-980plus/redesign/dev-plan-R1.status.json'));
const task=index.tasks.find(t=>t.id==='R1-001'),record=state.tasks.find(t=>t.id===task.id);
const delivery=JSON.parse(fs.readFileSync(task.evidenceDirectory+'delivery-5.json'));
for(const a of [...delivery.artifacts,...delivery.evidence])verifyArtifact(root,a);
verifyArtifact(root,record.submission.receipt);
const snapshot=gitSnapshot(root,task);
if(snapshot.sourceCommit!==delivery.sourceCommit||snapshot.dirtyDiffSha256!==delivery.dirtyDiffSha256)throw Error('Delivery source drift');
const startedAt=new Date().toISOString();
const unit=spawnSync(process.execPath,['--test','apps/official-site/tests/public-projection-bff.test.mjs','apps/official-site/tests/b13-official-site.test.mjs','apps/official-site/tests/b14-fe-005.test.mjs','apps/official-site/tests/website-entry.test.mjs'],{cwd:root,encoding:'utf8',windowsHide:true});
fs.writeFileSync(path.join(dir,'unit.log'),(unit.stdout||'')+(unit.stderr||''));
const probe=spawnSync(process.execPath,[path.resolve(task.evidenceDirectory+'reviewer-3/cache-probe.mjs')],{cwd:root,encoding:'utf8',windowsHide:true});
fs.writeFileSync(path.join(dir,'cache.log'),(probe.stdout||'')+(probe.stderr||''));
const cache=probe.status===0?JSON.parse(probe.stdout):null;
const result={startedAt,finishedAt:new Date().toISOString(),revision:state.revision,artifactsVerified:delivery.artifacts.length,evidenceVerified:delivery.evidence.length,snapshot,unitExit:unit.status,cacheProbeExit:probe.status,cache,scope:'independent units/current BFF VM; no build or browser integration rerun in this precheck'};
fs.writeFileSync(path.join(dir,'precheck.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify({revision:state.revision,artifacts:delivery.artifacts.length,evidence:delivery.evidence.length,unitExit:unit.status,cache}));
