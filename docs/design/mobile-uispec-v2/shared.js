  // 进度环：stroke-dashoffset 从满圈动画到目标（900ms，CSS 过渡）
  function setRing(ringEl, percentValue) {
    var circle = ringEl.querySelector('.ring__value');
    if (!circle) return;
    var r = circle.r.baseVal.value;
    var c = 2 * Math.PI * r;
    var value = Math.max(0, Math.min(100, percentValue));
    circle.style.strokeDasharray = String(c);
    circle.style.strokeDashoffset = String(c);
    void circle.getBoundingClientRect();
    requestAnimationFrame(function () {
      circle.style.strokeDashoffset = String(c * (1 - value / 100));
      ringEl.setAttribute('aria-label', ringEl.getAttribute('aria-label') || '完成 ' + value + '%');
    });
  }

