  // 任务行左滑：露出「稍后」操作。支持 pointer 拖拽 + API 直达展开。
  function initSwipeRows(root) {
    root.querySelectorAll('[data-swipe-row]').forEach(function (row) {
      if (row.dataset.swipeReady) return;
      row.dataset.swipeReady = '1';
      var inner = row.querySelector('.swipe-row__inner');
      var action = row.querySelector('.swipe-row__action');
      if (!inner || !action) return;
      var startX = null, startY = null, dx = 0, dragging = false, open = false;
      var ACTION_W = 108;

      function settle(nextOpen) {
        open = nextOpen;
        inner.style.transition = '';
        inner.style.transform = open ? 'translateX(' + (-ACTION_W) + 'px)' : 'translateX(0)';
        row.classList.toggle('is-open', open);
        action.setAttribute('tabindex', open ? '0' : '-1');
        action.setAttribute('aria-hidden', String(!open));
      }

      row.addEventListener('pointerdown', function (event) {
        if (event.pointerType === 'mouse' && event.button !== 0) return;
        startX = event.clientX;
        startY = event.clientY;
        dx = 0;
        dragging = false;
        inner.style.transition = 'none';
      });
      row.addEventListener('pointermove', function (event) {
        if (startX === null) return;
        var mx = event.clientX - startX;
        var my = event.clientY - startY;
        if (!dragging) {
          if (Math.abs(mx) < 8 || Math.abs(mx) < Math.abs(my)) return;
          dragging = true;
          try { row.setPointerCapture(event.pointerId); } catch (e) { /* 忽略 */ }
        }
        dx = Math.max(-ACTION_W - 24, Math.min(24, (open ? -ACTION_W : 0) + mx));
        inner.style.transform = 'translateX(' + dx + 'px)';
      });
      function endDrag() {
        if (startX === null) return;
        var wasDragging = dragging;
        startX = null;
        dragging = false;
        if (!wasDragging) return;
        settle(dx < -ACTION_W * 0.42);
      }
      row.addEventListener('pointerup', endDrag);
      row.addEventListener('pointercancel', endDrag);
      row.addEventListener('lostpointercapture', endDrag);

      action.addEventListener('click', function (event) {
        event.preventDefault();
        event.stopPropagation();
        settle(false);
        toast('已放到稍后，今天结束前都能做', 'info', 2200);
        row.dispatchEvent(new CustomEvent('uispec:snooze', { bubbles: true }));
      });
      // 已滑开时点击行主体先合上，避免误触进入课程
      inner.addEventListener('click', function (event) {
        if (open) { event.preventDefault(); settle(false); }
      }, true);

      row.uispecSwipe = { open: function () { settle(true); }, close: function () { settle(false); }, isOpen: function () { return open; } };
    });
  }

