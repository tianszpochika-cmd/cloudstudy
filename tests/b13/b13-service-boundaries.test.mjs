test('commerce-service enforces service-side JWT, idempotency, Outbox and a closed payment Gate', () => {
  assert.match(commerceSecurity, /oauth2ResourceServer/)
  assert.match(commerceSecurity, /anyRequest\(\)\.denyAll\(\)/)
  assert.match(commercePrincipal, /JwtAuthenticationToken/)
  assert.match(commercePrincipal, /tenant_id/)
  assert.doesNotMatch(commercePrincipal, /getHeader\s*\(/)
  assert.match(commerceHeaders, /x-role|x-b5-role|x-tenant-id|x-owner-id/i)

  assert.match(commerceApplication, /IdempotencyPort/)
  assert.match(commerceApplication, /idempotent\(/)
  assert.match(commerceApplication, /idempotency\.(find|save)/)
  assert.match(commerceApplication, /OutboxPort/)
  assert.match(commerceApplication, /outbox\.append/)
  assert.match(commerceConfig, /PaymentGate/)
  assert.match(commerceProperties, /false,\s*"DISABLED"/)
  assert.match(commerceYaml, /COMMERCE_PAYMENT_ENABLED:false/)
  assert.match(commerceSmoke, /PaymentGate\.disabled\(\)/)
  assert.match(commerceSmoke, /create order must be idempotent/)
  assert.match(commerceSmoke, /outbox\.events\(\)/)

  assert.doesNotMatch(commerceController, /X-B5-Role|X-Role|X-Tenant|X-Owner/i)
  assert.doesNotMatch(commerceSecurity, /requestMatchers\([^)]*\/providers\/\*\/callbacks[\s\S]*?permitAll\(\)/i, 'provider callbacks must not bypass service authentication')
  assert.match(commerceController, /paymentCallback\([^)]*Authentication/)
})

